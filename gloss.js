  // 把英文句子渲染成「词 + 中文」逐字翻译
  function gloss(text){
    var tokens = String(text).split(/(\s+)/);
    var out='';
    for(var i=0;i<tokens.length;i++){
      var t=tokens[i];
      if(t===''||/^\s+$/.test(t)){ out+=t; continue; }
      var m=t.match(/^([^A-Za-z]*)([A-Za-z][A-Za-z'\-]*)([^A-Za-z]*)$/);
      if(!m){ out+=t; continue; }
      var pre=m[1], word=m[2], post=m[3];
      var key=word.toLowerCase();
      if(key.length>2 && key.slice(-2)==="'s") key=key.slice(0,-2);
      var zh=DICT[key];
      out+=pre;
      if(zh) out+='<span class="gw" data-w="'+word+'">'+word+'<span class="gc">'+zh+'</span></span>';
      else out+='<span class="gw" data-w="'+word+'">'+word+'</span>';
      out+=post;
    }
    return out;
  }

  // 整篇逐字翻译：按句拆行，每行词对词
  function buildPGlossHTML(enText){
    var sents=String(enText).match(/[^.!?]+[.!?]*/g)||[enText];
    var h='<span class="glab">🔤 整篇逐字翻译（词对词）</span>';
    var n=0;
    for(var k=0;k<sents.length;k++){
      var s=sents[k].replace(/^\s+|\s+$/g,'');
      if(!s) continue;
      n++;
      h+='<div class="sline"><span class="sn">'+n+'.</span>'+gloss(s)+'</div>';
    }
    return h;
  }

  // 点击单词朗读（浏览器语音合成，零联网依赖；缺英文语音时退回系统默认 en-US 发音）
  function speak(word){
    word=String(word||'').replace(/^[\s'"]+|[\s'"]+$/g,'');
    if(!word) return;
    try{
      if(!('speechSynthesis' in window)) return;
      // 优先复用共享发音引擎（含 iOS 静音修复：resume + 全局引用 + 英文嗓音指派 + 防竞态）
      if(window.Speech && window.Speech.speak){ window.Speech.speak(word, 0.85); return; }
      // 兜底：自实现（旧逻辑 + iOS 修复）
      window.speechSynthesis.cancel();
      var u=new SpeechSynthesisUtterance(word);
      u.lang='en-US'; u.rate=0.85; u.pitch=1;
      var vs=window.speechSynthesis.getVoices();
      if(vs&&vs.length){
        for(var i=0;i<vs.length;i++){
          if(/^en[-_]?US/i.test(vs[i].lang)||/^en/i.test(vs[i].lang)){ u.voice=vs[i]; break; }
        }
      }
      window.__ttsUtt=u;
      try{ window.speechSynthesis.resume(); }catch(e){}
      setTimeout(function(){ try{ window.speechSynthesis.speak(u); }catch(e){} }, 60);
    }catch(e){}
  }
